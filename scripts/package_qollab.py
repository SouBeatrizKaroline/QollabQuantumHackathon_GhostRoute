"""Build Ghost Route's generated Qollab bundle from its canonical sources.

Run ``python scripts/package_qollab.py`` from any working directory. The
generated directory and ZIP live under dist/ and must not be committed.
"""

from __future__ import annotations

from pathlib import Path
import shutil
import sys
import zipfile


PROJECT_ROOT = Path(__file__).resolve().parents[1]
ROOT_FILES = ("sensor.py", "requirements.txt", "README.md", "LICENSE", "vercel.json")
SOURCE_DIRECTORIES = ("public", "scripts", "examples", "docs", "tests")
EXCLUDED_PARTS = {"__pycache__", ".pytest_cache", ".ruff_cache", ".git", ".venv"}
REQUIRED_FILES = (
    *ROOT_FILES,
    "public/index.html",
    "scripts/replay_session.py",
    "examples/session-seed-20261011.json",
)

PACKAGE_GUIDE = """# Ghost Route generated package

This directory was generated by `python scripts/package_qollab.py`. Edit the
canonical project sources, then regenerate it; do not edit or commit dist/.

Keep this directory structure when extracting the ZIP. The Python sensor
is at the package root, and scripts import it through their parent directory.

## Local quantum validation

From the extracted package root:

```sh
python -m pip install -r requirements.txt
python -m pytest tests -q
python sensor.py
python scripts/replay_session.py examples/session-seed-20261011.json
```

Use `python scripts/replay_session.py --help` for replay options. Browser
exports and the local Qiskit simulator need not produce identical sampled
counts; the replay validates the recorded inputs and sensor model.

On Windows, `scripts/setup_and_test.bat` creates a local .venv, installs the
requirements, runs validation and generates `docs/assets/ramsey-fringes.png`.

## Web interface

Open `public/index.html` with its assets directory beside it, or serve it with:

```sh
python -m http.server 8000 --directory public
```

The web interface samples the Ramsey model in JavaScript. It does not invoke
Qiskit or IonQ hardware. `sensor.py` is the canonical Qiskit module; this
package does not introduce a Qollab backend or runner contract. Configure the
Qollab runtime according to its supported execution interface before submitting.

This effort is supported by Qollab & IonQ
"""


def source_files() -> list[Path]:
    """List distributable sources without copying caches or linked targets."""
    missing = [name for name in REQUIRED_FILES if not (PROJECT_ROOT / name).is_file()]
    if missing:
        raise FileNotFoundError("Missing canonical source files: " + ", ".join(missing))
    files = [PROJECT_ROOT / name for name in ROOT_FILES]
    for directory_name in SOURCE_DIRECTORIES:
        directory = PROJECT_ROOT / directory_name
        if not directory.is_dir():
            raise FileNotFoundError(f"Missing source directory: {directory_name}")
        for source in directory.rglob("*"):
            relative = source.relative_to(PROJECT_ROOT)
            if any(part in EXCLUDED_PARTS for part in relative.parts):
                continue
            if source.is_symlink():
                raise ValueError(f"Linked source paths are not packaged: {relative}")
            if source.is_file() and source.suffix not in {".pyc", ".pyo", ".log"}:
                source.resolve().relative_to(PROJECT_ROOT)
                files.append(source)
    for source in files:
        if source.is_symlink():
            raise ValueError(f"Linked source paths are not packaged: {source.relative_to(PROJECT_ROOT)}")
        source.resolve().relative_to(PROJECT_ROOT)
    return sorted(files, key=lambda source: source.relative_to(PROJECT_ROOT).as_posix())


def build_package() -> tuple[Path, Path, int]:
    files = source_files()  # Validate before changing an existing generated bundle.
    dist = PROJECT_ROOT / "dist"
    dist.mkdir(exist_ok=True)
    if dist.is_symlink() or dist.resolve().parent != PROJECT_ROOT:
        raise ValueError("The generated dist directory must stay within this project")
    package = dist / "qollab"
    # Check the exact resolved recursive-delete target before removing it.
    if package.is_symlink() or package.resolve().parent != dist.resolve():
        raise ValueError("The generated qollab directory must stay within dist")
    if package.exists():
        if not package.is_dir():
            raise ValueError("dist/qollab must be a generated directory")
        shutil.rmtree(package)
    package.mkdir()
    for source in files:
        destination = package / source.relative_to(PROJECT_ROOT)
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, destination)
    (package / "PACKAGE_GUIDE.md").write_text(PACKAGE_GUIDE, encoding="utf-8")

    archive = dist / "ghost-route-qollab.zip"
    temporary_archive = dist / ".ghost-route-qollab.zip.tmp"
    for target in (archive, temporary_archive):
        if target.is_symlink() or target.resolve().parent != dist.resolve():
            raise ValueError("Generated archive paths must stay within dist")
    with zipfile.ZipFile(temporary_archive, "w", compression=zipfile.ZIP_DEFLATED) as output:
        for source in sorted(package.rglob("*")):
            if source.is_file():
                output.write(source, arcname="qollab/" + source.relative_to(package).as_posix())
    temporary_archive.replace(archive)
    return package, archive, len(files) + 1


def main() -> int:
    try:
        package, archive, count = build_package()
    except (OSError, ValueError) as error:
        print(f"Ghost Route packaging failed: {error}", file=sys.stderr)
        return 1
    print(f"Ghost Route: packaged {count} files")
    print(f"Directory: {package}")
    print(f"Archive:   {archive}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
